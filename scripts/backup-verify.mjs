// Server-only. Never import into the frontend. No scheduler; no production restore.
import mysql from 'mysql2/promise';
import { spawn } from 'node:child_process';
import { createReadStream, createWriteStream, existsSync } from 'node:fs';
import { readFile, writeFile, mkdir, mkdtemp, rm, open } from 'node:fs/promises';
import { pipeline } from 'node:stream/promises';
import { createHash, randomBytes } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';

const help = `Usage (Node 22+, server environment only):
  node --env-file=.env scripts/backup-verify.mjs backup <absolute-output.sql>
  node scripts/backup-verify.mjs verify <absolute-backup.sql>
  node scripts/backup-verify.mjs self-test
Source: DATABASE_URL / MYSQL_URL or DB_HOST, DB_PORT, DB_USER, DB_PASSWORD, DB_NAME.
Restore: BACKUP_VERIFY_HOST (loopback only), BACKUP_VERIFY_PORT, BACKUP_VERIFY_USER,
         BACKUP_VERIFY_PASSWORD. Creates then drops ONLY a random kl_verify_* DB.
MYSQL_BIN / MYSQLDUMP_BIN override CLI paths; Windows XAMPP auto-detected.
Pause operational writes/DDL during backup. SQL + manifest contain sensitive data.
Only verify trusted backups generated by this script; SQL is executable code.`;
const id = value => '`' + String(value).replaceAll('`', '``') + '`';
const token = () => randomBytes(10).toString('hex');
function config(verify = false) {
  if (verify) {
    const host = process.env.BACKUP_VERIFY_HOST || '127.0.0.1';
    if (!['127.0.0.1', 'localhost', '::1'].includes(host)) throw Error('Restore restricted to loopback; use an isolated local database server.');
    return { host, port: Number(process.env.BACKUP_VERIFY_PORT || 3306), user: process.env.BACKUP_VERIFY_USER || '', password: process.env.BACKUP_VERIFY_PASSWORD || '' };
  }
  const url = process.env.DATABASE_URL || process.env.MYSQL_URL;
  if (url) {
    const u = new URL(url);
    if (u.protocol !== 'mysql:') throw Error('Expected mysql URL.');
    return { host: u.hostname, port: Number(u.port || 3306), user: decodeURIComponent(u.username), password: decodeURIComponent(u.password), database: decodeURIComponent(u.pathname.slice(1)) };
  }
  return { host: process.env.DB_HOST || '127.0.0.1', port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER || '', password: process.env.DB_PASSWORD || '', database: process.env.DB_NAME || '' };
}
function validate(c, source = false) {
  if (!c.user || !Number.isInteger(c.port) || c.port < 1 || c.port > 65535 || (source && !c.database)) throw Error('Missing/invalid database configuration.');
}
const connect = c => mysql.createConnection({ ...c, charset: 'utf8mb4', dateStrings: true, supportBigNumbers: true, bigNumberStrings: true, connectTimeout: 10000 });
function binary(name) {
  return process.env[name === 'mysql' ? 'MYSQL_BIN' : 'MYSQLDUMP_BIN'] || (process.platform === 'win32' && existsSync(`C:/xampp/mysql/bin/${name}.exe`) ? `C:/xampp/mysql/bin/${name}.exe` : name);
}
async function cli(name, c, args, file, importing = false) {
  // Password absent from argv/logs. Child-only MYSQL_PWD; not a global env mutation.
  const child = spawn(binary(name), ['--no-defaults', '--protocol=tcp', `--host=${c.host}`, `--port=${c.port}`, `--user=${c.user}`, '--default-character-set=utf8mb4', ...args], {
    env: { ...process.env, MYSQL_PWD: c.password }, windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'],
  });
  child.stderr.resume(); // Never expose database errors/SQL/credentials in terminal output.
  const done = new Promise((yes, no) => {
    child.on('error', () => no(Error(`${name} unavailable; configure ${name === 'mysql' ? 'MYSQL_BIN' : 'MYSQLDUMP_BIN'}.`)));
    child.on('close', code => code === 0 ? yes() : no(Error(`${name} failed (exit ${code}); inspect server-side permissions/client compatibility privately.`)));
  });
  try {
    if (importing) {
      child.stdout.resume();
      await Promise.all([done, pipeline(createReadStream(file), child.stdin)]);
    } else {
      child.stdin.end();
      await Promise.all([done, pipeline(child.stdout, createWriteStream(file, { flags: 'w', mode: 0o600 }))]);
    }
  } catch (error) { child.kill(); throw error; }
}
async function digest(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return hash.digest('hex');
}
async function inventory(c) {
  const db = await connect(c);
  try {
    const [tables] = await db.query('SELECT TABLE_NAME name, ENGINE engine, TABLE_TYPE type FROM information_schema.TABLES WHERE TABLE_SCHEMA = ? ORDER BY TABLE_NAME', [c.database]);
    if (!tables.length || tables.some(t => t.type !== 'BASE TABLE' || t.engine !== 'InnoDB')) throw Error('Only nonempty InnoDB base-table databases supported; views/other engines require a reviewed native backup.');
    for (const [table, column] of [['TRIGGERS', 'TRIGGER_SCHEMA'], ['ROUTINES', 'ROUTINE_SCHEMA'], ['EVENTS', 'EVENT_SCHEMA']]) {
      const [rows] = await db.query(`SELECT COUNT(*) n FROM information_schema.${table} WHERE ${column} = ?`, [c.database]);
      if (Number(rows[0].n)) throw Error('Triggers/routines/events require a separately reviewed native backup.');
    }
    await db.query('SET TRANSACTION ISOLATION LEVEL REPEATABLE READ');
    await db.query('START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY');
    const result = [];
    for (const t of tables) {
      const [ddl] = await db.query(`SHOW CREATE TABLE ${id(t.name)}`);
      // ponytail: table materialized in RAM; use a streaming exporter for databases exceeding server RAM.
      const [rows] = await db.query(`SELECT * FROM ${id(t.name)}`);
      const hashes = rows.map(row => createHash('sha256').update(JSON.stringify(row)).digest('hex')).sort();
      result.push({ table: t.name, rows: rows.length, schema: createHash('sha256').update(ddl[0]['Create Table']).digest('hex'), data: createHash('sha256').update(hashes.join('\n')).digest('hex') });
    }
    await db.rollback();
    return result;
  } finally { await db.end(); }
}
async function backup(c, file) {
  validate(c, true);
  if (existsSync(file) || existsSync(file + '.json')) throw Error('Output already exists; choose a fresh backup filename.');
  await mkdir(dirname(file), { recursive: true, mode: 0o700 });
  const before = await inventory(c);
  let created = false;
  try {
    const reserved = await open(file, 'wx', 0o600);
    created = true;
    await reserved.close();
    await cli('mysqldump', c, ['--single-transaction', '--quick', '--hex-blob', '--skip-lock-tables', '--skip-triggers', '--', c.database], file);
    assert.deepEqual(await inventory(c), before, 'Source changed during backup; retry in maintenance window.');
    const sha256 = await digest(file);
    await writeFile(file + '.json', JSON.stringify({ version: 1, createdAt: new Date().toISOString(), sha256, tables: before }, null, 2) + '\n', { flag: 'wx', mode: 0o600 });
    console.log(JSON.stringify({ backup: 'PASS', sha256, tables: before.length, rows: before.reduce((n, t) => n + t.rows, 0) }));
  } catch (error) {
    if (created) await rm(file, { force: true });
    throw error;
  }
}
async function verify(c, file) {
  validate(c);
  const manifest = JSON.parse(await readFile(file + '.json', 'utf8'));
  if (manifest.version !== 1 || !Array.isArray(manifest.tables) || manifest.sha256 !== await digest(file)) throw Error('Backup manifest/hash invalid.');
  const database = 'kl_verify_' + token();
  const admin = await connect(c);
  let created = false;
  try {
    await admin.query(`CREATE DATABASE ${id(database)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    created = true;
    await cli('mysql', c, ['--binary-mode=1', '--', database], file, true);
    assert.deepEqual(await inventory({ ...c, database }), manifest.tables, 'Restored schema/data mismatch.');
    console.log(JSON.stringify({ restore: 'PASS', sha256: manifest.sha256, tables: manifest.tables.length, rows: manifest.tables.reduce((n, t) => n + t.rows, 0) }));
  } finally {
    try { if (created) await admin.query(`DROP DATABASE ${id(database)}`); }
    finally { await admin.end(); }
  }
}
async function selfTest() {
  // Ignores DATABASE_URL/DB_* entirely; fixture creation is loopback-only.
  const c = config(true);
  validate(c);
  const database = 'kl_verify_fixture_' + token();
  const dir = await mkdtemp(join(tmpdir(), 'kitchenlog-backup-'));
  const file = join(dir, 'fixture.sql');
  const admin = await connect(c);
  let created = false;
  try {
    await admin.query(`CREATE DATABASE ${id(database)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`);
    created = true;
    await admin.query(`CREATE TABLE ${id(database)}.evidence (id INT PRIMARY KEY, note TEXT, photo LONGBLOB, optional_value TEXT NULL) ENGINE=InnoDB`);
    await admin.query(`CREATE TABLE ${id(database)}.empty_table (id INT PRIMARY KEY) ENGINE=InnoDB`);
    await admin.query(`INSERT INTO ${id(database)}.evidence VALUES (?, ?, ?, ?), (?, ?, ?, ?)`, [1, 'Dapur ✓ café \' \\ \n', Buffer.from([0, 255, 10]), null, 2, 'closing', Buffer.from('photo fixture'), '']);
    await backup({ ...c, database }, file);
    await verify(c, file);
    const manifest = JSON.parse(await readFile(file + '.json', 'utf8'));
    await writeFile(file + '.json', JSON.stringify({ ...manifest, sha256: 'tampered' }));
    await assert.rejects(verify(c, file), /manifest\/hash invalid/);
    await assert.rejects(backup({ ...c, database }, file), /already exists/);
    console.log('PASS real local dump/restore: Unicode, quotes, newline, binary, NULL, empty table; tamper/overwrite rejected; disposable databases removed on exit.');
  } finally {
    try { if (created) await admin.query(`DROP DATABASE ${id(database)}`); }
    finally { await admin.end(); await rm(dir, { recursive: true, force: true }); }
  }
}
try {
  const [mode, path, ...extra] = process.argv.slice(2);
  if (extra.length) throw Error(help);
  if (mode === 'self-test' && !path) await selfTest();
  else if (mode === 'backup' && path) await backup(config(), resolve(path));
  else if (mode === 'verify' && path) await verify(config(true), resolve(path));
  else if (!mode || mode === '--help') console.log(help);
  else throw Error(help);
} catch (error) {
  // Assertion diagnostics and driver messages may contain private row/connection data.
  console.error(error?.code ? `FAIL database/client operation (${String(error.code).replace(/[^A-Z0-9_]/g, '')}); inspect configuration privately.` : `FAIL ${error instanceof assert.AssertionError ? 'Verification mismatch; preserve backup, investigate source changes/schema compatibility.' : error.message}`);
  process.exitCode = 1;
}
